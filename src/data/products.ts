// Deterministic pickers — same slug always produces the same content.
// ----------------------------------------------------------------------------
function hash(s: string) {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
  return h;
}
function pick<T>(arr: readonly T[], seed: number, offset = 0): T {
  return arr[(seed + offset) % arr.length];
}
function pickN<T>(arr: readonly T[], seed: number, n: number): T[] {
  const out: T[] = [];
  const used = new Set<number>();
  let i = 0;
  while (out.length < Math.min(n, arr.length) && i < arr.length * 3) {
    const idx = (seed + i * 7 + 3) % arr.length;
    if (!used.has(idx)) { used.add(idx); out.push(arr[idx]); }
    i++;
  }
  return out;
}

