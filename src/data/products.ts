// Base price per 100g by category, tuned per product with a small offset.
const BASE_PER_100G: Record<string, number> = {
  "blended-pure-spices": 80,
  "whole-spices": 95,
  "grounded-spices": 60,
};

function pricesFor(category: string, sizes: Size[], seed: number): PriceMap {
  const base = BASE_PER_100G[category] ?? 70;
  // vary ±30% deterministically
  const factor = 0.7 + ((seed % 60) / 100); // 0.70 – 1.29
  const per100 = Math.max(25, Math.round(base * factor));
  const gramMap: Record<Size, number> = {
    "20g": 20, "50g": 50, "100g": 100, "200g": 200, "500g": 500, "1000g": 1000,
  };
  const out: PriceMap = {};
  for (const s of sizes) {
    // slight bulk discount for larger sizes
    const grams = gramMap[s];
    const discount = grams >= 500 ? 0.9 : grams >= 200 ? 0.95 : 1;
    const raw = (per100 / 100) * grams * discount;
    // round to nearest ₹5
    out[s] = Math.max(10, Math.round(raw / 5) * 5);
  }
  return out;
}


